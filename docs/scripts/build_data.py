"""Regenerate docs/data.js from the benchmark CSVs in this repo.

Run from the repo root:  python3 docs/scripts/build_data.py
Every number on the project page comes from these files; nothing is typed in by hand.
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def rows(path):
    with open(ROOT / path, newline="") as f:
        return list(csv.DictReader(f))


def grouped(path, key):
    out = {}
    for r in rows(path):
        out.setdefault(r[key], []).append([int(r["n"]), float(r["time_ms"])])
    return {k: sorted(v) for k, v in out.items()}


data = {
    "serial": sorted([int(r["n"]), float(r["time_ms"])] for r in rows("serial/results.csv")),
    "openmp": grouped("openmp/results.csv", "threads"),
    "mpi": grouped("mpi/results.csv", "processes"),
    "cuda": grouped("cuda/results.csv", "block_size"),
    "jax": grouped("additional/results.csv", "backend"),
    "sources": {
        "serial": "serial/results.csv",
        "openmp": "openmp/results.csv",
        "mpi": "mpi/results.csv",
        "cuda": "cuda/results.csv",
        "jax": "additional/results.csv",
    },
}

out = ROOT / "docs" / "data.js"
out.write_text(
    "// Generated by docs/scripts/build_data.py from the repo's results.csv files. Do not edit.\n"
    "window.FFT_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n"
)
print("wrote", out.relative_to(ROOT))
